"""Opt-in native JSON-schema transport for the local vLLM Shadow experiment.

Only a known input echo is constrained; no classification answer is pinned and no
reply is repaired. This module does not import BLINK, start services, or send HTTP.
"""
from __future__ import annotations

from collections import Counter
import copy
import hashlib
import json
import re

from common import Refuse

MODE = 'vllm_native_raw_query'
NATIVE_MODES = {MODE, 'vllm_native_json_schema'}
QUERY_MARKER = '【本輪待判斷輸入】\n'


def digest(value) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def current_query(messages: list[dict]) -> str:
    """Read the last current-user envelope, NOT examples or member history.

    This is the exact suffix generated by the reviewed _build_current_user_content
    contract. Ambiguous duplicate markers, missing delimiters and trailing prose
    are rejected, not guessed. Interior Unicode, quotes and newlines are preserved.
    """
    if not messages or messages[-1].get('role') != 'user':
        raise Refuse('Native intent binding requires a final current-user message')
    text = messages[-1].get('content')
    if not isinstance(text, str) or text.count(QUERY_MARKER) != 1:
        raise Refuse('Native intent current-input marker is missing or ambiguous')
    suffix = text.split(QUERY_MARKER, 1)[1]
    if len(suffix) < 3 or not suffix.startswith('「') or not suffix.endswith('」'):
        raise Refuse('Native intent current-input envelope is incompatible')
    query = suffix[1:-1]
    if not query.strip() or len(query.encode('utf-8')) > 65536:
        raise Refuse('Native intent current-input length is invalid')
    return query


def attach(out: dict, meta: dict, original_payload: dict, path: str) -> tuple[dict, dict]:
    """Add a native response_format while leaving messages/sampling untouched.

    json_object requests intentionally retain their existing prompt-only handling.
    Unknown schemas containing raw_query are refused instead of binding the wrong
    field. Native schema itself is private transient metadata, stripped by handler.
    """
    if meta.get('output_format_type') != 'json_schema':
        return out, meta
    schema = meta.get('schema')
    if not isinstance(schema, dict):
        raise Refuse('Native schema request has no JSON schema')
    fmt = ((original_payload.get('text') or {}).get('format')
           if path.rstrip('/') == '/v1/responses'
           else original_payload.get('response_format')) or {}
    inner = fmt.get('json_schema', fmt)
    name = inner.get('name', 'shadow_schema')
    if not isinstance(name, str) or not re.fullmatch(r'[A-Za-z0-9_-]{1,64}', name):
        raise Refuse('Native schema name is invalid')
    bound = copy.deepcopy(schema)
    props = schema.get('properties', {})
    is_intent = name == 'intent_parse_result'
    query = None
    if is_intent:
        if (schema.get('type') != 'object' or not isinstance(props, dict)
                or 'raw_query' not in schema.get('required', [])
                or not isinstance(props.get('raw_query'), dict)
                or props['raw_query'].get('type') != 'string'
                or not isinstance(props.get('intent_type'), dict)):
            raise Refuse('Native intent schema contract is incompatible')
        query = current_query(out['messages'])
        # Preserve/narrow existing constraints; never replace an incompatible one.
        import jsonschema
        try:
            jsonschema.validate(query, props['raw_query'])
        except Exception:
            raise Refuse('Current input does not satisfy the original raw_query field') from None
        bound['properties']['raw_query']['enum'] = [query]
    elif isinstance(props, dict) and 'raw_query' in props:
        raise Refuse('Unrecognized raw_query schema; no inferred binding applied')
    # Pinning intent_type or any other answer field is deliberately absent.
    fmt_out = {'type': 'json_schema', 'json_schema': {
        'name': name, 'strict': True, 'schema': bound}}
    result = dict(out)
    result['response_format'] = fmt_out
    info = dict(meta)
    info.update(schema_mode=MODE if is_intent else 'vllm_native_json_schema',
                native_schema_requested=True, schema_name=name,
                raw_query_bound=is_intent,
                raw_query_binding_source='final_current_user_envelope' if is_intent else None,
                raw_query_chars=len(query) if query is not None else None,
                classification_labels_pinned=False, response_repaired=False,
                native_request_fingerprint={'response_format_sha256': digest(fmt_out),
                                            'messages_sha256': digest(result['messages'])},
                _native_schema=bound)
    return result, info


def wire_metadata(raw) -> dict:
    """Metadata-only outgoing proxy HTTP observation; contains no content values."""
    try:
        if isinstance(raw, bytes):
            if len(raw) > 4 * 1024 * 1024: return {'status': 'unavailable'}
            raw = raw.decode('utf-8')
        if not isinstance(raw, str) or len(raw) > 4 * 1024 * 1024:
            return {'status': 'unavailable'}
        body = json.loads(raw)
        fmt = body.get('response_format')
        if not isinstance(fmt, dict) or fmt.get('type') != 'json_schema':
            return {'status': 'not_native_json_schema'}
        if not isinstance(body.get('messages'), list): return {'status': 'unavailable'}
        return {'status': 'observed', 'response_format_sha256': digest(fmt),
                'messages_sha256': digest(body['messages']),
                'observation_point': 'proxy_outgoing_http'}
    except Exception:
        return {'status': 'unavailable'}


def transport_proof(models: list[dict], dependencies: list[dict], *, require_native: bool = False) -> dict:
    """Compare per-case request fingerprints as a multiset, not invented IDs.

    LiteLLM may omit upstream X-Request-ID. Matching uses the complete schema and
    messages fingerprints plus selected destination, with multiplicity. This is
    Python HTTP observation, NOT an assertion about native kernel execution.
    """
    def key(row, fingerprint):
        f = fingerprint or {}
        a, b = f.get('response_format_sha256'), f.get('messages_sha256')
        port = row.get('provider_port', row.get('port'))
        if not (isinstance(a, str) and re.fullmatch('[a-f0-9]{64}', a)
                and isinstance(b, str) and re.fullmatch('[a-f0-9]{64}', b)
                and isinstance(port, int)):
            return None
        return port, a, b
    wanted = [m for m in models if m.get('native_schema_requested')]
    expected = Counter()
    malformed = 0
    for m in wanted:
        k = key(m, m.get('native_request_fingerprint'))
        if k is None: malformed += 1
        else: expected[k] += 1
    observed = Counter()
    for row in dependencies:
        if (row.get('role') != 'proxy' or not row.get('model_http')
                or row.get('path') != '/v1/chat/completions'):
            continue
        f = row.get('native_wire') or {}
        k = key(row, f)
        if f.get('status') == 'observed' and k is not None:
            observed[k] += 1
    missing = sum(max(0, count - observed[k]) for k, count in expected.items())
    extra = sum(max(0, observed[k] - count) for k, count in expected.items())
    return {'pass': malformed == 0 and missing == 0 and extra == 0 and (bool(wanted) or not require_native),
            'native_evidence_required': require_native,
            'native_calls': len(wanted), 'matched': len(wanted) - malformed - missing,
            'missing': missing, 'malformed': malformed, 'duplicate_attempts': extra,
            'correlation_scope': 'case-local destination/schema/messages multiset; not inferred request IDs',
            'kernel_decoding_verified': False}
