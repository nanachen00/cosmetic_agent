def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def target_path(root: Path, relative: str) -> Path:
    parts=PurePosixPath(relative)
    if parts.is_absolute() or '..' in parts.parts:
        raise RuntimeError('Unsafe update path')
    p=root.joinpath(*parts.parts)
    for q in (p,*p.parents):
        if q==root:break
        if q.is_symlink():raise RuntimeError('Refuse symlink in update target: '+str(q))
    return p


def inspect(root: Path, data: dict) -> list[str]:
    for journal in (root/'.state').glob('*/journal.json'):
        if json.loads(journal.read_text()).get('cleanup_pass') is not True:
            raise RuntimeError('Unresolved benchmark recovery state: '+str(journal.parent))
    errors=[]; changed=[]
    for name,old in data['baseline'].items():
        p=target_path(root,name)
        now=sha(p.read_bytes()) if p.is_file() else None
        entry=data['files'].get(name)
        new=entry['sha256'] if entry else old
        if now not in {old,new}:errors.append(name+' does not match reviewed harness baseline/update')
    for name,entry in data['files'].items():
        p=target_path(root,name)
        content=entry['text'].encode('utf-8')
        if sha(content)!=entry['sha256']:raise RuntimeError('Embedded update digest mismatch: '+name)
        if name.endswith('.py'):ast.parse(entry['text'],filename=name)
        now=sha(p.read_bytes()) if p.is_file() else None
        if name not in data['baseline'] and now not in {None,entry['sha256']}:
            errors.append('New-file path already contains different content: '+name)
        if now!=entry['sha256']:changed.append(name)
    if errors:raise RuntimeError('\n'.join(errors))
    return changed


def atomic_write(path: Path, content: bytes, mode: int) -> None:
    path.parent.mkdir(parents=True,exist_ok=True)
    fd,name=tempfile.mkstemp(prefix='.'+path.name+'.update-',dir=path.parent)
    try:
        with os.fdopen(fd,'wb') as stream:
            stream.write(content);stream.flush();os.fsync(stream.fileno())
        os.chmod(name,mode)
        os.replace(name,path)
    finally:
        if os.path.exists(name):os.unlink(name)


def verify_final(root: Path, data: dict) -> None:
    for line in data['files']['MANIFEST.sha256']['text'].splitlines():
        digest,name=line.split('  ',1)
        if sha(target_path(root,name).read_bytes())!=digest:
            raise RuntimeError('Post-apply manifest mismatch: '+name)


def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--target-dir',default='/var/lib/jenkins/tomod/ops/local-llm-path-benchmark')
    parser.add_argument('--check-only',action='store_true')
    args=parser.parse_args()
    root=Path(args.target_dir).resolve(strict=True)
    if root.name!='local-llm-path-benchmark' or root.parent.name!='ops' or 'cosmetic-agent' in root.parts:
        raise RuntimeError('Target must be the existing ops/local-llm-path-benchmark harness, not production source')
    data=json.loads(zlib.decompress(base64.b64decode(_PAYLOAD)))
    changed=inspect(root,data)
    if args.check_only:
        print(json.dumps({'check':'PASS','target':str(root),'would_update':changed,'writes':False},ensure_ascii=False,indent=2))
        return 0
    locks=[]
    try:
        # Same cooperative lock used by bench.py. Also exclude the all-phases wrapper.
        for name in ('.verified-workflow.lock','.benchmark.lock'):
            p=root/name
            if p.is_symlink():raise RuntimeError('Lock path is a symlink')
            stream=p.open('a');locks.append(stream)
            fcntl.flock(stream,fcntl.LOCK_EX|fcntl.LOCK_NB)
        changed=inspect(root,data)
        if not changed:
            verify_final(root,data);print('[ALREADY APPLIED] No files changed');return 0
        stamp=dt.datetime.now(dt.timezone.utc).strftime('%Y%m%d-%H%M%S-%f')
        backup=root/'backups'/('shadow-smoke-'+stamp)
        backup.mkdir(parents=True,exist_ok=False)
        print('[BACKUP]',backup,flush=True)
        before={}
        for name in changed:
            p=target_path(root,name)
            raw=p.read_bytes() if p.is_file() else None
            mode=stat.S_IMODE(p.stat().st_mode) if p.is_file() else data['files'][name]['mode']
            before[name]=(raw,mode)
            if raw is not None:
                q=backup/name;q.parent.mkdir(parents=True,exist_ok=True);q.write_bytes(raw);q.chmod(0o600)
        journal={'status':'prepared','target':str(root),'files':changed,
                 'new_files':[n for n,(raw,_) in before.items() if raw is None],
                 'original_modes':{n:mode for n,(_,mode) in before.items()}}
        (backup/'install.json').write_text(json.dumps(journal,indent=2)+'\n')
        previous_term=signal.getsignal(signal.SIGTERM)
        def interrupted(signum,frame):raise KeyboardInterrupt('Installer interrupted')
        signal.signal(signal.SIGTERM,interrupted)
        written=[]
        try:
            # The manifest is written last. Do not run the harness during an update.
            order=[n for n in changed if n!='MANIFEST.sha256']+(['MANIFEST.sha256'] if 'MANIFEST.sha256' in changed else [])
            for name in order:
                entry=data['files'][name]
                written.append(name)
                atomic_write(target_path(root,name),entry['text'].encode(),before[name][1])
                print('[UPDATED]',name,flush=True)
            verify_final(root,data)
        except BaseException:
            for name in reversed(written):
                p=target_path(root,name);raw,mode=before[name]
                if raw is None:p.unlink(missing_ok=True)
                else:atomic_write(p,raw,mode)
            journal['status']='rolled_back';(backup/'install.json').write_text(json.dumps(journal,indent=2)+'\n')
            raise
        finally:
            signal.signal(signal.SIGTERM,previous_term)
        journal['status']='APPLY_PASS';(backup/'install.json').write_text(json.dumps(journal,indent=2)+'\n')
        print('[APPLY PASS] Shadow harness updated; no service was signalled/restarted.')
        print('Next: PYTHON_BIN=/opt/conda/bin/python3 bash run_verified_shadow_tests.sh --ack-shared-data-services')
        return 0
    finally:
        for stream in reversed(locks):stream.close()

